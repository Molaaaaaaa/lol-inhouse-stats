export type HelpKey = keyof typeof HELP;

export function isHelpKey(key: string): key is HelpKey {
  return Object.hasOwn(HELP, key);
}

/**
 * 키에 해당하는 설명. 없는 키·빈 키는 빈 문자열 — 툴팁 쪽이 "안 띄움" 으로 처리한다.
 * 함수형 항목은 payload 를 받아 그때그때 만든다. payload 가 없으면 기준선 없음으로 본다.
 */
export function helpText(key: string | null | undefined, payload?: HelpPayload | null): string {
  if (!key || !isHelpKey(key)) return '';
  const v: HelpEntry = HELP[key];
  return typeof v === 'function' ? v(payload ?? { baseline: null }) : v;
}

/**
 * 솔랭 기준선 표본 문구 — "12,345판, 패치 15.1 이후". 툴팁과 기준선 패널 본문이 같이 쓴다.
 * games 는 티어별 dict 다({GOLD:…, MASTER:…}) — 합쳐서 쓴다.
 */
export function baseSampleText(baseline: Baseline | null | undefined): string {
  const g: unknown = baseline?.games;
  const n = g && typeof g === 'object'
    ? Object.values(g as Record<string, unknown>).reduce<number>((s, v) => s + (Number(v) || 0), 0)
    : Number(g) || 0;
  const patch = baseline?.patch_min;
  return (n ? `${n.toLocaleString()}판` : '솔랭 표본') + (patch ? `, 패치 ${patch} 이후` : '');
}
